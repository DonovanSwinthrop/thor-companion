// PokeDaisy — WIDE: the overworld past the GBA's 240 px, rebuilt from the game's memory (pk_wide.c).
#pragma once

#include <stdint.h>

struct mCore;

#define PK_WIDE_W 240
#define PK_WIDE_H 160
/** Most GBA pixels drawn beside the game, per side (21:9 at 160 tall needs 67). */
#define PK_WIDE_MAX_MARGIN 96

/** Engines (the layouts below): FireRed / LeafGreen (and the CFRU hacks), Emerald, Ruby / Sapphire, every language and
 * revision, and pokeemerald-expansion. */
enum {
    PK_WIDE_FAMILY_FR = 1,
    PK_WIDE_FAMILY_EM = 2,
    PK_WIDE_FAMILY_RS = 3,
    PK_WIDE_FAMILY_RS_JA = 4,   // Japanese Ruby / Sapphire: gMain and subsprites as FireRed / Emerald have them
    PK_WIDE_FAMILY_EX = 5,      // pokeemerald-expansion (Lazarus, SoulGold): Emerald's map, ObjectEvent.spriteId moved
};

/** A game's config: its addresses (per release: pk_wide_games.h, generated by scripts/gen_wide_tables.py),
 * then its engine's layout (pk_wide.c's FAMILIES). */
enum {
    PK_WIDE_VMAP,              // struct BackupMapLayout { s32 width, height; u16 *map; }
    PK_WIDE_MAP_HEADER,        // gMapHeader: +0 mapLayout, +0xC connections
    PK_WIDE_MAP_GROUPS,        // gMapGroups (ROM): the connected maps' headers
    PK_WIDE_SAVE_BLOCK1_PTR,   // -> pos (s16 x, y); Ruby / Sapphire: the block itself (PK_WIDE_SAVE_STATIC)
    PK_WIDE_CAMERA_OFFSET,     // sFieldCameraOffset: u8 xPixelOffset, yPixelOffset, xTileOffset, yTileOffset
    PK_WIDE_OBJECT_EVENTS,     // gObjectEvents[16], 0x24 each
    PK_WIDE_SPRITES,           // gSprites[64], 0x44 each
    PK_WIDE_COORD_OFFSET,      // gSpriteCoordOffsetX (s16)
    PK_WIDE_COORD_OFFSET_Y,    // gSpriteCoordOffsetY (s16): right after X, but not in Ruby / Sapphire
    PK_WIDE_SPRITE_ORDER,      // u8[64], BuildOamBuffer's order
    PK_WIDE_GMAIN,             // gMain: inBattle is bit 1 of +PK_WIDE_INBATTLE_OFF
    PK_WIDE_MAP_GROUPS_XOR,    // not an address: what gMapGroups' entries are XORed with (Unbound), else 0
    PK_WIDE_NORMAL_BG3,        // not an address: what DrawMetatile puts on BG3 under a NORMAL metatile (0x3014; Unbound 0)
    PK_WIDE_METATILE_SIZE,     // not an address: 16 (two layers), 24 (triple-layer: BG3, BG2, BG1 - Lazarus)
    PK_WIDE_METATILE_MASK,     // not an address: a map cell's metatile id bits - 0x3FF, SoulGold 0x7FF (all ones = none)
    PK_WIDE_PRIMARY_OVERRIDE,  // not an address: the primary tileset's metatiles where a hack changed them (SoulGold 1024), else 0
    PK_WIDE_PAN_OFF,           // not an address: where sHorizontal / sVerticalCameraPan sit from sFieldCameraOffset - 8
                               // after it (agbcc pads the struct to 8 bytes); a gcc build places them as it likes
    PK_WIDE_ADDRS,
    PK_WIDE_PRIMARY_METATILES = PK_WIDE_ADDRS,   // 640 FireRed, 512 Emerald
    PK_WIDE_ATTR_OFFSET,       // struct Tileset's metatileAttributes: 0x14 FireRed, 0x10 Emerald
    PK_WIDE_ATTR_SIZE,         // 4 (u32, FireRed) or 2 (u16, Emerald)
    PK_WIDE_LAYER_SHIFT,       // the layer type's bits: 29 (FireRed) / 12 (Emerald)
    PK_WIDE_LAYER_MASK,        // 3 / 0xF
    PK_WIDE_BORDER_SIZED,      // 1: MapLayout.borderWidth / Height at +0x18 / +0x19 (FireRed); 0: Emerald's 2x2
    PK_WIDE_SAVE_STATIC,       // 1: SaveBlock1 sits at PK_WIDE_SAVE_BLOCK1_PTR (Ruby / Sapphire: no pointer)
    PK_WIDE_INBATTLE_OFF,      // gMain's inBattle byte: 0x439, Ruby / Sapphire 0x43D
    PK_WIDE_SUBSPRITE_SIZE,    // struct Subsprite: 4 (s8 x, y), Ruby / Sapphire 8 (u16 x, y; agbcc pads it to 4 bytes)
    PK_WIDE_SPRITE_ID_OFF,     // ObjectEvent.spriteId: 4, expansion 0x23 (its graphicsId is a u16)
    PK_WIDE_CONFIG_SIZE
};

/** Sets the running game by its ROM's CRC32 (pk_wide_games.h); 0 or an unknown one switches WIDE off.
 * Returns whether WIDE knows it. */
int pk_wide_configure(uint32_t crc);

/** Whether WIDE has the ROM with this CRC32 (no core needed). */
int pk_wide_knows(uint32_t crc);

/** Forgets what earlier frames left (a state load, a new core, a rewind). */
void pk_wide_reset(void);

/**
 * Emu thread, after each frame: `out` ((240 + 2 * margin) x 160) gets `frame` (the core's
 * 240 x 160) in the middle and the rebuilt overworld beside it - or, wherever that can't be
 * checked (title, battles, menus, transitions), a glow spread from the frame's own edges,
 * crossfaded. With `centre` set (headless checks), the
 * rebuild of the middle 240 x 160 goes there too, sprites included. Returns how much of the
 * strips is the map, 0..256 (the rest is the glow).
 */
int pk_wide_frame(struct mCore* core, const uint32_t* frame, uint32_t* out, int margin, uint32_t* centre);

/** What the last frame's strips showed: nothing drawn (the glow), the map, or a battle. */
enum { PK_WIDE_MODE_NONE, PK_WIDE_MODE_MAP, PK_WIDE_MODE_BATTLE };
int pk_wide_last_mode(void);

/** How the last frame went, for logs and mgba_dump: tilemap match 0..1000, -1 if none was tried. */
int pk_wide_last_score(void);
/** 1 if the last frame's sprites came from an earlier snapshot (the RAM was mid-update). */
int pk_wide_last_torn(void);
