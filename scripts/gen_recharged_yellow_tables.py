#!/usr/bin/env python3
"""Generates Pokémon Recharged Yellow's display tables from the ROMs the user owns
(Jaizu's FireRed decomp rebuild, BPRE rev 0, 16 MB, no source; nothing is
downloaded).

    scripts/gen_recharged_yellow_tables.py <rom.gba> [<rom.gba> ...]

Pass any of v1.8.0 / v1.9.0 / v1.9.4 / v1.9.7 (all four to check them against each
other): every release moved its tables but kept their contents byte for byte, so
one set of names serves all four. Writes {SpeciesNames,MoveData,ItemNames,
MapSecNames}RechargedYellow.kt into the app's data package. Item descriptions
aren't written: the app reads them from the player's ROM (RomItemText,
NativeConfig.itemDescs - each release's gItems is printed below).

Where each table is: the GF ROM header (0x08000100, pokefirered's struct
GFRomHeader) points at gSpeciesNames (11-byte names, FireRed's species ids, in
capitals), gMoveNames (13 bytes, title-cased: "Pound"), gBaseStats, gItems and
gBattleMoves. gItems is the hack's own 48-byte struct Item: name[18], price +0x12,
holdEffect +0x14 / param +0x15, description +0x18, importance +0x1C, pocket +0x1E
(1 Items, 2 Medicine, 3 Poké Balls, 4 TMs & HMs, 5 Berries, 6 Key Items), no
itemId field - the slot is the id (vanilla's 1..376, then its own: Mints,
Bottle Caps, item fossils, Power Items, DexNav, Blueprints up to 408). sMapNames
is the pointer table that references "Pallet Town" (FireRed's map sections 0x58..,
title-cased). gBaseStats' types and gender ratios, gBattleMoves' type / power and
gTypeEffectiveness are vanilla FireRed's to the byte (checked by hash below), so
the app keeps FireRed's tables for those.

Its GUIDE area data (GuideAreasRechargedYellow{V180,V190,V194,}Gen.kt) comes from gen_guide_areas_rom.py,
per release (each moved items and gifts), with the sizes of the script commands it added or changed:

    OPS=0e=1,94=1,aa=10,b1=3,c8=1,cc=1,d3=3,d4=1,d5=3,d6=1,d7=8,d8=1,d9=1,da=1,db=5,dc=3,dd=4,de=4,df=5,e0=8,e1=4,e2=6,e4=7,e5=3,e7=5
    gen_guide_areas_rom.py "Recharged Yellow v1.8.0.gba" RECHARGED_YELLOW_V180 --items 0x08807a38,48,0x1e,6 \\
        --max-species 412 --no-hidden-flags --ops $OPS,67=25,e6=26 --kotlin
    ... v1.9.0 (V190, --items 0x088074ac) / v1.9.4 (V194, 0x088e74b0): --ops $OPS,67=25,e6=26,e8=5,e9=1
    ... v1.9.7 (RECHARGED_YELLOW, 0x0890f960): --ops $OPS,67=29,e6=30,e8=5,e9=1
"""
import hashlib
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_emerald_lang_tables import CHARS  # noqa: E402

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "kotlin",
                       "com", "pokedaisy", "app", "companion", "data")
B = 0x08000000
# sha1 -> (version, sMapNames). The rest comes from the GF ROM header.
ROMS = {
    "be5033598e91d0e80fa93e551406f02a7876d7c2": ("1.8.0", 0x08891BC8),
    "ac30d1ed80e75104a3fb92f71e2b9a51c26e80c8": ("1.9.0", 0x08891684),
    "7d9fae6cf31c07bc7fa5cf7afe137ad5385cefb1": ("1.9.4", 0x08971688),
    "ed60654d7525ba005bfc8f799bf0ecba2ef08a2e": ("1.9.7", 0x0899A498),
}
SPECIES_COUNT, MOVES_COUNT, ITEMS_COUNT = 412, 355, 409
FIRST_MAPSEC, SECTIONS = 0x58, 0xCA - 0x58
ITEM_STRIDE, ITEM_POCKET_OFF = 48, 0x1E
# Vanilla FireRed's bytes, hashed from a retail ROM: species types + gender ratio
# (gBaseStats +6, +7, +0x10 for species 0..411), gBattleMoves type / power for moves
# 0..354, and gTypeEffectiveness up to its 0xFF terminator.
FIRERED_TYPES_GENDER_SHA1 = "6f842049a949baa026e168bde832f6c0a642e551"
FIRERED_MOVE_STATS_SHA1 = "8ead8ccbe22fa8c3cf0d6d99c705522f17c9ec6b"
FIRERED_TYPE_CHART_SHA1 = "29d73ba911b78e5b448dd8f493dac2d0b1d460d1"
CH = dict(CHARS)


def text(d, a, maxlen):
    out = []
    for b in d[a - B:a - B + maxlen]:
        if b == 0xFF:
            break
        if b in (0xFA, 0xFB, 0xFE):
            out.append(" ")
            continue
        if b not in CH:
            return None
        out.append(CH[b])
    s = " ".join("".join(out).split())
    return s if s and set(s) != {"?"} else None


def u8(d, a):
    return d[a - B]


def u32(d, a):
    return struct.unpack_from("<I", d, a - B)[0]


def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def header(what, versions):
    return (f"package com.pokedaisy.app.companion.data\n\n"
            f"// GENERATED by scripts/gen_recharged_yellow_tables.py from the Pokemon Recharged Yellow ROMs\n"
            f"// ({', '.join('v' + v for v in versions)}: the same tables) - do not hand-edit. {what}\n")


def write(name, body):
    path = os.path.join(OUT_DIR, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(body)
    print("wrote", os.path.relpath(path))


def tables(d, map_names):
    hdr = struct.unpack_from("<10I", d, 0x100 + 8 + 32)
    species_names, move_names = hdr[7], hdr[8]
    rest = struct.unpack_from("<7I", d, 0x100 + 8 + 32 + 40 + 36 + 20 + 48 + 4)
    base_stats, items, battle_moves = rest[0], rest[3], rest[4]
    print(f"  gSpeciesNames {species_names:#x}, gMoveNames {move_names:#x}, gBaseStats {base_stats:#x}, "
          f"gItems {items:#x}, gBattleMoves {battle_moves:#x}, sMapNames {map_names:#x}")

    tg = bytes(b for i in range(SPECIES_COUNT) for b in (u8(d, base_stats + 28 * i + 6), u8(d, base_stats + 28 * i + 7),
                                                         u8(d, base_stats + 28 * i + 0x10)))
    assert hashlib.sha1(tg).hexdigest() == FIRERED_TYPES_GENDER_SHA1, "species types / gender ratios differ from FireRed's"
    ms = bytes(b for i in range(MOVES_COUNT) for b in (u8(d, battle_moves + 12 * i + 1), u8(d, battle_moves + 12 * i + 2)))
    assert hashlib.sha1(ms).hexdigest() == FIRERED_MOVE_STATS_SHA1, "move types / power differ from FireRed's"
    # gTypeEffectiveness by its first three {atk, def, x10} triplets (NORMAL -> ROCK / STEEL, FIRE -> FIRE).
    chart = d.find(bytes.fromhex("0005050008050a0a05"))
    end = chart
    while d[end] != 0xFF:
        end += 3
    assert hashlib.sha1(d[chart:end + 1]).hexdigest() == FIRERED_TYPE_CHART_SHA1, "type chart differs from FireRed's"

    names = {}
    for i in range(1, SPECIES_COUNT):
        n = text(d, species_names + 11 * i, 11)
        if n:
            names[i] = n
    assert names[25] == "PIKACHU" and names[277] == "TREECKO" and names[411] == "CHIMECHO" and 252 not in names

    moves = {}
    for i in range(1, MOVES_COUNT):
        n = text(d, move_names + 13 * i, 13)
        if n:
            a = battle_moves + 12 * i
            moves[i] = (n, u8(d, a + 2), u8(d, a + 1))
    assert moves[33] == ("Tackle", 0, 35) and moves[84][0] == "ThunderShock" and moves[354][0] == "Psycho Boost"

    item_names = {}
    for slot in range(1, ITEMS_COUNT):
        a = items + ITEM_STRIDE * slot
        n = text(d, a, 18)
        if n and u8(d, a + ITEM_POCKET_OFF) <= 6:
            item_names[slot] = n
    assert item_names[13] == "Potion" and item_names[361] == "Town Map" and item_names[407] == "DexNav" and 55 not in item_names

    secs = {}
    for i in range(SECTIONS):
        p = u32(d, map_names + 4 * i)
        n = text(d, p, 32) if B <= p < B + len(d) else None
        if n:
            secs[FIRST_MAPSEC + i] = n
    assert secs[0x59] == "Viridian City" and secs[0xC4] == "Celadon Dept."
    return names, moves, item_names, secs


def main():
    if len(sys.argv) < 2:
        sys.exit(f"usage: {sys.argv[0]} <rom.gba> [<rom.gba> ...]")
    results, versions = [], []
    for path in sys.argv[1:]:
        d = open(path, "rb").read()
        sha1 = hashlib.sha1(d).hexdigest()
        if sha1 not in ROMS:
            sys.exit(f"{path}: not a known Recharged Yellow release (sha1 {sha1})")
        version, map_names = ROMS[sha1]
        print(f"v{version}:")
        versions.append(version)
        results.append(tables(d, map_names))
    for r in results[1:]:
        assert r == results[0], "the releases' tables differ - generate them per version"
    names, moves, items, secs = results[0]
    versions.sort()

    write("SpeciesNamesRechargedYellow.kt", header("gSpeciesNames, FireRed's species ids, in the\n"
          "// game's capitals (its types and gender ratios are FireRed's).\n", versions) +
          "val speciesNamesRechargedYellow: Map<Int, String> = mapOf(\n" +
          "".join(f"    {i} to {kstr(n)},\n" for i, n in sorted(names.items())) + ")\n")
    write("MoveDataRechargedYellow.kt", header("gMoveNames (title-cased, as the game prints\n"
          "// them) + gBattleMoves type / power (FireRed's).\n", versions) +
          "val moveDataRechargedYellow: Map<Int, MoveInfo> = mapOf(\n" +
          "".join(f"    {i} to MoveInfo({kstr(n)}, {t}, {p}),\n" for i, (n, t, p) in sorted(moves.items())) + ")\n")
    write("ItemNamesRechargedYellow.kt", header("gItems names by item id (its 48-byte records\n"
          "// have no itemId: the slot is the id).\n", versions) +
          "val itemNamesRechargedYellow: Map<Int, String> = mapOf(\n" +
          "".join(f"    {i} to {kstr(n)},\n" for i, n in sorted(items.items())) + ")\n")
    write("MapSecNamesRechargedYellow.kt", header("sMapNames by map section id: FireRed's sections\n"
          "// under the game's title-cased names (the MAP keeps FireRed's boxes and region map).\n", versions) +
          "val mapSecNamesRechargedYellow: Map<Int, String> = mapOf(\n" +
          "".join(f"    {i} to {kstr(n)},\n" for i, n in sorted(secs.items())) + ")\n")
    print(f"{len(names)} species, {len(moves)} moves, {len(items)} items, {len(secs)} map sections")


if __name__ == "__main__":
    main()
