#!/usr/bin/env python3
"""Generates what Pokémon Ultra Violet v1.22 names differently from FireRed, from
the ROM the user owns (a 16 MB binary hack of FireRed 1.0, BPRE rev 0 code with
the game code PUVV; no source, nothing is downloaded).

    scripts/gen_ultra_violet_tables.py <ultra-violet-v1.22.gba> <firered-rev0.gba>

Writes UltraVioletGen.kt into the app's data package: the species / move / item /
map-section names and species types that differ from retail FireRed rev 0 (sha1
41cb23d8...), by FireRed's own ids. The app runs Ultra Violet as FIRERED with these
laid over the shared tables (ActiveTables' `ultraViolet`).

Ultra Violet keeps every table at rev 0's address, edited in place (FireRed 1.0's
literal pools still name them): gSpeciesNames 0x08245EE0, gBaseStats 0x08254784
(28 bytes, types at +6 / +7), gMoveNames 0x08247094 + gBattleMoves 0x08250C04,
gItems 0x083DB028 and sMapNames 0x083F1CAC (pointers from MAPSEC 0x58). What it
changed: GYARADOS is WATER / DRAGON, item 12 is the WHITE BALL, 347 the LAND DEED,
species 252 (an unused slot) a WHITE HAND, and a few map sections (CATACOMBS,
DREAD MOUNTAIN, ...; three read "000" in the game). Its moves are FireRed's.
Names are title-cased like the shared tables (FireRed's own casing puts them back
in capitals on screen).
"""
import hashlib
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_emerald_lang_tables import CHARS  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "kotlin",
                   "com", "pokedaisy", "app", "companion", "data", "UltraVioletGen.kt")
SHA1 = "3b6c51d8fb6b513bdd01b7bda3ed8965bc985d58"
FIRERED_REV0_SHA1 = "41cb23d8dccc8ebd7c649cd8fbb58eeace6e2fdc"
B = 0x08000000
SPECIES_NAMES, SPECIES_COUNT = 0x08245EE0, 412
BASE_STATS = 0x08254784
MOVE_NAMES, BATTLE_MOVES, MOVES_COUNT = 0x08247094, 0x08250C04, 355
ITEMS, ITEMS_COUNT = 0x083DB028, 375
MAP_NAMES, FIRST_MAPSEC, SECTIONS = 0x083F1CAC, 0x58, 109
CH = dict(CHARS)


def text(d, a, maxlen):
    out = []
    for b in d[a - B:a - B + maxlen]:
        if b == 0xFF:
            break
        if b in (0xFA, 0xFB, 0xFE):
            out.append(" ")
            continue
        if b not in CH:
            return None
        out.append(CH[b])
    s = " ".join("".join(out).split())
    return s if s and set(s) != {"?"} else None


def u8(d, a):
    return d[a - B]


def u32(d, a):
    return struct.unpack_from("<I", d, a - B)[0]


def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def title(s):
    """The shared tables' casing: "WHITE BALL" -> "White Ball", "4-POINTS ISLE" -> "4-Points Isle"."""
    out, start = [], True
    for c in s:
        out.append(c.upper() if start else c.lower())
        start = not c.isalpha() and c not in "‘’'"
    return "".join(out)


def species(d):
    return {i: text(d, SPECIES_NAMES + 11 * i, 11) for i in range(1, SPECIES_COUNT)}


def types(d):
    return {i: (u8(d, BASE_STATS + 28 * i + 6), u8(d, BASE_STATS + 28 * i + 7)) for i in range(1, SPECIES_COUNT)}


def moves(d):
    return {i: (text(d, MOVE_NAMES + 13 * i, 13), u8(d, BATTLE_MOVES + 12 * i + 2), u8(d, BATTLE_MOVES + 12 * i + 1))
            for i in range(1, MOVES_COUNT)}


def items(d):
    return {i: text(d, ITEMS + 44 * i, 14) for i in range(1, ITEMS_COUNT)}


def mapsecs(d):
    out = {}
    for i in range(SECTIONS):
        p = u32(d, MAP_NAMES + 4 * i)
        out[FIRST_MAPSEC + i] = text(d, p, 32) if B <= p < B + len(d) else None
    return out


def diff(a, b):
    return {k: v for k, v in b.items() if v is not None and a.get(k) != v}


def main():
    if len(sys.argv) != 3:
        sys.exit(f"usage: {sys.argv[0]} <ultra-violet-v1.22.gba> <firered-rev0.gba>")
    uv, fr = (open(p, "rb").read() for p in sys.argv[1:])
    if hashlib.sha1(uv).hexdigest() != SHA1:
        sys.exit(f"not Ultra Violet v1.22 (sha1 {SHA1})")
    if hashlib.sha1(fr).hexdigest() != FIRERED_REV0_SHA1:
        sys.exit(f"not retail FireRed rev 0 (sha1 {FIRERED_REV0_SHA1})")

    sp = diff(species(fr), species(uv))
    ty = diff(types(fr), types(uv))
    mv = diff(moves(fr), moves(uv))
    it = diff(items(fr), items(uv))
    ms = diff(mapsecs(fr), mapsecs(uv))
    assert sp == {252: "WHITE HAND"}, sp
    assert ty[130] == (11, 16), ty
    assert it[12] == "WHITE BALL" and it[347] == "LAND DEED", it
    assert ms[0x9C] == "CATACOMBS" and ms[0xAB] == "DREAD MOUNTAIN", ms

    head = ("package com.pokedaisy.app.companion.data\n\n"
            "// GENERATED by scripts/gen_ultra_violet_tables.py from the Pokemon Ultra Violet v1.22 ROM\n"
            f"// (sha1 {SHA1[:8]}...) against retail FireRed rev 0 - do not hand-edit. What Ultra Violet\n"
            "// names / types differently, by FireRed's ids (ActiveTables lays these over the shared tables).\n\n")
    body = (
        "internal val speciesNamesUltraViolet: Map<Int, String> = mapOf(\n" +
        "".join(f"    {i} to {kstr(title(n))},\n" for i, n in sorted(sp.items())) + ")\n\n" +
        "internal val speciesTypesUltraViolet: Map<Int, SpeciesTypes> = mapOf(\n" +
        "".join(f"    {i} to SpeciesTypes({a}, {b}),\n" for i, (a, b) in sorted(ty.items())) + ")\n\n" +
        "internal val moveDataUltraViolet: Map<Int, MoveInfo> = mapOf(\n" +
        "".join(f"    {i} to MoveInfo({kstr(title(n))}, {t}, {p}),\n" for i, (n, t, p) in sorted(mv.items())) + ")\n\n" +
        "internal val itemNamesUltraViolet: Map<Int, String> = mapOf(\n" +
        "".join(f"    {i} to {kstr(title(n))},\n" for i, n in sorted(it.items())) + ")\n\n" +
        "/** Section names only: the map, its boxes and cursor grid are FireRed's, byte for byte. */\n"
        "internal val mapSecNamesUltraViolet: Map<Int, String> = mapOf(\n" +
        "".join(f"    {i} to {kstr(title(n))},\n" for i, n in sorted(ms.items())) + ")\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(head + body)
    print("wrote", os.path.relpath(OUT))
    print(f"{len(sp)} species, {len(ty)} types, {len(mv)} moves, {len(it)} items, {len(ms)} map sections")


if __name__ == "__main__":
    main()
